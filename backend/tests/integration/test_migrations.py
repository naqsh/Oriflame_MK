"""Alembic against a real, throwaway PostgreSQL (OR-004).

Uses TEST_POSTGRES_URL (see conftest.py). These tests downgrade to base, so they must
never point at the hosted Supabase project; conftest refuses Supabase hosts.
"""

from collections.abc import Iterator

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import Engine, inspect, text
from sqlalchemy.orm import Session

from backend.tests.conftest import alembic_config

pytestmark = pytest.mark.db


@pytest.fixture
def migration_config(
    monkeypatch: pytest.MonkeyPatch, migrated_engine: Engine, test_database_url: str
) -> Iterator[Config]:
    monkeypatch.setenv("POSTGRES_URL", test_database_url)
    config = alembic_config()
    yield config
    command.upgrade(config, "head")  # leave the shared test database at head


def test_upgrade_head_on_empty_database(migration_config: Config, migrated_engine: Engine) -> None:
    command.downgrade(migration_config, "base")
    command.upgrade(migration_config, "head")

    with migrated_engine.connect() as connection:
        version = connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
    assert version == "005_referral_clicks"


def test_downgrade_base_then_upgrade_head(migration_config: Config) -> None:
    command.downgrade(migration_config, "base")
    command.upgrade(migration_config, "head")


def test_downgrade_one_then_upgrade_head(migration_config: Config, migrated_engine: Engine) -> None:
    command.downgrade(migration_config, "-1")
    assert "referral_clicks" not in inspect(migrated_engine).get_table_names()
    command.upgrade(migration_config, "head")
    assert "referral_clicks" in inspect(migrated_engine).get_table_names()


def test_downgrade_catalogue_schema_removes_tables_and_enum(
    migration_config: Config, migrated_engine: Engine
) -> None:
    command.downgrade(migration_config, "001_baseline")
    with migrated_engine.connect() as connection:
        leftover = connection.execute(
            text(
                "SELECT count(*) FROM pg_type WHERE typname = 'sync_run_status' "
                "OR typname IN ('products', 'categories')"
            )
        ).scalar_one()
    assert leftover == 0  # tables and the enum type are gone
    command.upgrade(migration_config, "head")


def test_no_drift_between_models_and_migrations(migration_config: Config) -> None:
    command.check(migration_config)  # raises AutogenerateDiffsDetected on drift


def test_rls_enabled_on_every_public_table(migrated_engine: Engine) -> None:
    with migrated_engine.connect() as connection:
        without_rls = connection.execute(
            text(
                "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
                "WHERE n.nspname = 'public' AND c.relkind = 'r' AND NOT c.relrowsecurity"
            )
        ).scalars()
        assert list(without_rls) == []


def test_db_session_is_usable(db_session: Session) -> None:
    """The rollback fixture yields a working session on the migrated database."""
    assert isinstance(db_session, Session)
    assert db_session.execute(text("SELECT 1")).scalar_one() == 1
