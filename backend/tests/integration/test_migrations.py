"""Alembic against a real, throwaway PostgreSQL (OR-004).

Needs TEST_POSTGRES_URL (CI service container or local `supabase start`, set up in
OR-007). Never point it at the hosted Supabase project: these tests drop the schema.
"""

import os
from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import Engine, text

from backend.app.core.config import load_settings
from backend.app.db.session import create_db_engine

REPO_ROOT = Path(__file__).resolve().parents[3]

pytestmark = pytest.mark.skipif(
    not os.environ.get("TEST_POSTGRES_URL"),
    reason="Needs a real PostgreSQL via TEST_POSTGRES_URL (CI service container, OR-007)",
)


@pytest.fixture
def alembic_config(monkeypatch: pytest.MonkeyPatch) -> Iterator[Config]:
    monkeypatch.setenv("POSTGRES_URL", os.environ["TEST_POSTGRES_URL"])
    config = Config(str(REPO_ROOT / "alembic.ini"))
    command.downgrade(config, "base")
    yield config
    command.downgrade(config, "base")


@pytest.fixture
def engine(alembic_config: Config) -> Iterator[Engine]:
    db_engine = create_db_engine(load_settings())
    yield db_engine
    db_engine.dispose()


def test_upgrade_head_on_empty_database(alembic_config: Config, engine: Engine) -> None:
    command.upgrade(alembic_config, "head")

    with engine.connect() as connection:
        version = connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
    assert version == "001_baseline"


def test_downgrade_base_then_upgrade_head(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")
    command.upgrade(alembic_config, "head")


def test_no_drift_between_models_and_migrations(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")

    command.check(alembic_config)  # raises AutogenerateDiffsDetected on drift


def test_rls_enabled_on_every_public_table(alembic_config: Config, engine: Engine) -> None:
    command.upgrade(alembic_config, "head")

    with engine.connect() as connection:
        without_rls = connection.execute(
            text(
                "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
                "WHERE n.nspname = 'public' AND c.relkind = 'r' AND NOT c.relrowsecurity"
            )
        ).scalars()
        assert list(without_rls) == []
